// Writes supabase/nova-install-bundle.sql: every new migration, in the one order they must run,
// as one file to paste into the Supabase SQL editor (staging first). Each part is safe to run twice.
// Re-run this script after changing any of them; scripts/verify_local_all.mjs checks it is current.
import fs from 'node:fs';
import crypto from 'node:crypto';

export const ORDER = [
  'business-agents', 'business-registration', 'customer-journey', 'revive-proof', 'card-payments',
  'outbound-email', 'team-dispatch', 'reviews', 'business-channels', 'job-photos',
].map((n) => `supabase/${n}-migration-standalone.sql`).concat('supabase/zz-public-schema-lockdown-standalone.sql');

export function bundle() {
  const parts = ORDER.map((f) => {
    const sql = fs.readFileSync(f, 'utf8');
    if (/^\\[a-z]/m.test(sql)) throw new Error(`${f} holds a psql command; the SQL editor cannot run it`);
    return `-- ===== ${f} (sha256 ${crypto.createHash('sha256').update(sql).digest('hex').slice(0, 12)}) =====\n${sql.trim()}\n`;
  });
  return `-- Nova install bundle: ${ORDER.length} migrations in order. Generated by scripts/build_install_bundle.mjs; do not edit.\n-- Run on STAGING first, check, then production. Safe to run twice. Never re-run 20261114001055 or 20261114001136.\n\n${parts.join('\n')}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  fs.writeFileSync('supabase/nova-install-bundle.sql', bundle());
  console.log(`supabase/nova-install-bundle.sql: ${ORDER.length} migrations`);
}
