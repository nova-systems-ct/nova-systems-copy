// LOCAL STAGING — a real Supabase stack (Auth, Postgres, PostgREST, Storage, local mail) in Docker on this computer.
// Isolated: it only ever talks to 127.0.0.1. Nothing here reads .env.local (production) or touches a hosted project.
//
//   node scripts/local/staging.mjs check       # prerequisites (Docker running, disk)
//   node scripts/local/staging.mjs up          # supabase start + write .env.local-staging (git-ignored)
//   node scripts/local/staging.mjs migrate     # apply supabase/migration-manifest.json in order (idempotent)
//   node scripts/local/staging.mjs provision   # test owner + representative + Nova org + demo workspace
//   node scripts/local/staging.mjs serve       # app on http://localhost:5180 (Vite + the real api/*.js handlers)
//   node scripts/local/staging.mjs serve --lan # same, also reachable from an iPad on this Wi-Fi (sign-in required; Supabase stays private) — docs/LOCAL_STAGING.md
//   node scripts/local/staging.mjs worker      # background worker against the local stack
//   node scripts/local/staging.mjs down        # stop containers (data volume is kept)
//
// Secrets: the local stack's keys and the generated test-account passwords are written only to git-ignored files
// (.env.local-staging, .env.local-staging-accounts). They are never printed.
import fs from 'node:fs';
import path from 'node:path';
import http from 'node:http';
import os from 'node:os';
import crypto from 'node:crypto';
import { spawn, execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const CLI = ['--yes', 'supabase@2.121.0'];
const ENV_FILE = path.join(ROOT, '.env.local-staging');
const ACCOUNTS_FILE = path.join(ROOT, '.env.local-staging-accounts');
const APP_PORT = 5180; const API_PORT = 8790;
const cmd = process.argv[2];
const npx = process.platform === 'win32' ? 'npx.cmd' : 'npx';
const die = (m) => { console.error(`✗ ${m}`); process.exit(1); };

function supabase(args, { capture = false } = {}) {
  if (capture) return execFileSync(npx, [...CLI, ...args], { cwd: ROOT, encoding: 'utf8', shell: process.platform === 'win32', stdio: ['ignore', 'pipe', 'pipe'] });
  execFileSync(npx, [...CLI, ...args], { cwd: ROOT, stdio: 'inherit', shell: process.platform === 'win32' });
  return '';
}
function readEnv() {
  if (!fs.existsSync(ENV_FILE)) die('No .env.local-staging yet — run: node scripts/local/staging.mjs up');
  const env = Object.fromEntries(fs.readFileSync(ENV_FILE, 'utf8').split(/\r?\n/).filter((l) => /^[A-Z_][A-Z0-9_]*=/.test(l)).map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)]));
  assertLocal(env.SUPABASE_URL, 'SUPABASE_URL'); assertLocal(env.LOCAL_DB_URL, 'LOCAL_DB_URL');
  return env;
}
function assertLocal(url, name) {
  let h; try { h = new URL(url).hostname; } catch { die(`${name} is not a URL`); }
  if (!['127.0.0.1', 'localhost', '::1'].includes(h)) die(`${name} points at ${h}; local staging only ever uses 127.0.0.1`);
}
const jwtRole = (t) => { try { return JSON.parse(Buffer.from(String(t).split('.')[1], 'base64url').toString()).role; } catch { return null; } };

async function check() {
  let ok = true;
  try { execFileSync('docker', ['info', '--format', '{{.ServerVersion}}'], { stdio: ['ignore', 'pipe', 'pipe'] }); console.log('✓ Docker is running'); }
  catch { ok = false; console.log('✗ Docker is not installed or not running (needs WSL 2 + Docker Desktop; see docs/LOCAL_STAGING.md)'); }
  try { console.log(`✓ Supabase CLI ${supabase(['--version'], { capture: true }).trim()}`); } catch { ok = false; console.log('✗ Supabase CLI could not run through npx'); }
  if (!ok) process.exit(1);
}

async function up() {
  await check();
  supabase(['start']);
  writeEnv();
}
function writeEnv() {
  const raw = supabase(['status', '-o', 'json'], { capture: true });
  const s = JSON.parse(raw.slice(raw.indexOf('{')));
  const api = s.API_URL; const db = s.DB_URL; const anon = s.ANON_KEY; const service = s.SERVICE_ROLE_KEY;
  assertLocal(api, 'API_URL'); assertLocal(db, 'DB_URL');
  // The backend sends the key as "Authorization: Bearer" — it must be the legacy JWT keys, not sb_publishable/sb_secret.
  if (jwtRole(anon) !== 'anon' || jwtRole(service) !== 'service_role') die('The local stack did not report legacy JWT anon/service_role keys; the current code requires them');
  const lines = {
    SUPABASE_URL: api, SUPABASE_SERVICE_ROLE_KEY: service, VITE_SUPABASE_URL: api, VITE_SUPABASE_ANON_KEY: anon,
    LOCAL_DB_URL: db, LOCAL_MAIL_URL: s.MAILPIT_URL || s.INBUCKET_URL || '', APP_BASE_URL: `http://localhost:${APP_PORT}`,
    SALES_EMAIL_MODE: 'dry_run', WAVE1_SEND_ENABLED: 'false', DEMO_MAX_PER_IP_PER_DAY: '500', // local only: every local visitor is 127.0.0.1
    OPS_KILL_SWITCH: 'false', DEMO_IP_SALT: crypto.randomBytes(12).toString('hex'),
  };
  fs.writeFileSync(ENV_FILE, `# LOCAL STAGING ONLY — generated by scripts/local/staging.mjs; git-ignored; never copy into Vercel.\n${Object.entries(lines).map(([k, v]) => `${k}=${v}`).join('\n')}\n`, { mode: 0o600 });
  console.log(`✓ wrote ${path.basename(ENV_FILE)} (keys not printed). Local mail viewer: ${lines.LOCAL_MAIL_URL || 'see `supabase status`'}`);
}

async function pgClient(env) {
  const require = createRequire(path.join(ROOT, '.testenv', 'package.json'));
  const pg = require('pg');
  const c = new pg.Client({ connectionString: env.LOCAL_DB_URL }); await c.connect(); return c;
}
async function migrate() {
  const env = readEnv(); const c = await pgClient(env);
  await c.query('create schema if not exists nova_local; create table if not exists nova_local.migrations (file text primary key, sha256 text not null, applied_at timestamptz not null default now())');
  const order = JSON.parse(fs.readFileSync(path.join(ROOT, 'supabase/migration-manifest.json'), 'utf8')).order.map((x) => (typeof x === 'string' ? x : x.file));
  for (const f of order) {
    const sql = fs.readFileSync(path.join(ROOT, f), 'utf8'); const sha = crypto.createHash('sha256').update(sql).digest('hex');
    const prev = (await c.query('select sha256 from nova_local.migrations where file=$1', [f])).rows[0];
    if (prev?.sha256 === sha) { console.log(`= ${f}`); continue; }
    try { await c.query(sql); await c.query('insert into nova_local.migrations (file, sha256) values ($1,$2) on conflict (file) do update set sha256=excluded.sha256, applied_at=now()', [f, sha]); console.log(`${prev ? '↻' : '+'} ${f}`); }
    catch (e) { await c.end(); die(`${f}: ${e.message}`); }
  }
  await c.query("notify pgrst, 'reload schema'");
  await c.end(); console.log(`✓ ${order.length} migrations in manifest order`);
}

async function provision() {
  const env = readEnv(); Object.assign(process.env, env);
  const admin = async (method, p, body) => { const r = await fetch(`${env.SUPABASE_URL}/auth/v1/${p}`, { method, headers: { apikey: env.SUPABASE_SERVICE_ROLE_KEY, Authorization: `Bearer ${env.SUPABASE_SERVICE_ROLE_KEY}`, 'Content-Type': 'application/json' }, body: body ? JSON.stringify(body) : undefined }); const t = await r.text(); let j; try { j = JSON.parse(t); } catch { j = t; } return { status: r.status, body: j }; };
  const c = await pgClient(env);
  const accounts = fs.existsSync(ACCOUNTS_FILE) ? Object.fromEntries(fs.readFileSync(ACCOUNTS_FILE, 'utf8').split(/\r?\n/).filter((l) => l.includes('=')).map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)])) : {};
  async function user(key, email, name) {
    const existing = (await c.query('select id from auth.users where email=$1', [email])).rows[0];
    if (existing) return existing.id;
    const password = `Nv-${crypto.randomBytes(12).toString('base64url')}`;
    const r = await admin('POST', 'admin/users', { email, password, email_confirm: true, user_metadata: { full_name: name } });
    if (r.status >= 300) die(`could not create ${email}: ${r.status} ${JSON.stringify(r.body).slice(0, 160)}`);
    accounts[`${key}_EMAIL`] = email; accounts[`${key}_PASSWORD`] = password; return r.body.id;
  }
  const ownerId = await user('OWNER', 'owner@nova-local.test', 'Local Test Owner');
  const repId = await user('REP', 'rep@nova-local.test', 'Local Test Representative');
  let nova = (await c.query("select id from organizations where kind='nova_internal' order by created_at limit 1")).rows[0]?.id;
  if (!nova) nova = (await c.query("insert into organizations (name, slug, kind) values ('Nova Systems (LOCAL STAGING)','nova-local','nova_internal') returning id")).rows[0].id;
  const member = async (uid, role) => { if (!(await c.query('select 1 from organization_members where organization_id=$1 and staff_user_id=$2', [nova, uid])).rows.length) await c.query("insert into organization_members (organization_id, member_type, staff_user_id, role, status) values ($1,'staff',$2,$3,'active')", [nova, uid, role]); };
  // The representative follows the hiring flow's state (api/_sales/hiring.js): candidate role + candidate rep record +
  // an enrollment in every program. The owner activates them in the dashboard once training and documents are done.
  await member(ownerId, 'nova_super_admin'); await member(repId, 'nova_sales_candidate');
  await c.query("update organization_members set role='nova_sales_candidate' where organization_id=$1 and staff_user_id=$2 and role='nova_sales' and not exists (select 1 from sales_reps where user_id=$2 and status='active')", [nova, repId]);
  await c.query("insert into sales_reps (user_id, organization_id, display_name, status, manager_user_id) values ($1,$2,'Local Test Representative','candidate',$3) on conflict do nothing", [repId, nova, ownerId]);
  await c.query("insert into academy_enrollments (staff_user_id, organization_id, program_id, status) select $1, $2, id, 'not_started' from academy_programs on conflict (staff_user_id, program_id) do nothing", [repId, nova]);
  fs.writeFileSync(ACCOUNTS_FILE, `# LOCAL STAGING test accounts — git-ignored; local stack only.\n${Object.entries(accounts).map(([k, v]) => `${k}=${v}`).join('\n')}\n`, { mode: 0o600 });
  await c.end();
  // Demo workspace through the supported owner-only API operation, signed in as the owner (real Supabase Auth).
  const pw = accounts.OWNER_PASSWORD; if (!pw) die('owner password unknown (accounts file missing) — reset it in Studio, then rerun');
  const tok = await fetch(`${env.SUPABASE_URL}/auth/v1/token?grant_type=password`, { method: 'POST', headers: { apikey: env.VITE_SUPABASE_ANON_KEY, 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'owner@nova-local.test', password: pw }) }).then((r) => r.json());
  if (!tok.access_token) die('owner sign-in failed');
  const { makeCaller } = await import('../testenv/call.mjs');
  const call = makeCaller((await import('../../api/client.js')).default);
  const r = await call({ resource: 'demo', op: 'setup', method: 'POST', body: {}, token: tok.access_token });
  console.log(r.status === 200 && r.body.ready ? '✓ demo workspace ready' : `✗ demo workspace: ${r.status} ${JSON.stringify(r.body).slice(0, 160)}`);
  // Nova as its own first installation (LOCAL): the same owner actions the dashboard performs — hours, a form token,
  // an approved complimentary consultation service, and an approved booking agreement. Re-runnable.
  const ops = (op, body, method = 'POST') => call({ resource: 'ops', op, method, body: { organization_id: nova, ...body }, token: tok.access_token });
  const hours = Object.fromEntries(['mon', 'tue', 'wed', 'thu', 'fri'].map((d) => [d, [{ start: '09:00', end: '17:00' }]]));
  const st = await ops('settings', { timezone: 'America/New_York', business_hours: hours, display_name: 'Nova Systems', industry: 'Business operations', hold_minutes: 30, lead_time_hours: 2, booking_horizon_days: 21 });
  const w = await call({ resource: 'wave1', op: 'settings', method: 'POST', query: { organization_id: nova }, body: { organization_id: nova, timezone: 'America/New_York', business_hours: hours, ...(await (async () => { const s = (await pgClient(env)); const has = (await s.query('select form_token from wave1_org_settings where organization_id=$1', [nova])).rows[0]?.form_token; await s.end(); return has ? {} : { rotate_form_token: true }; })()) }, token: tok.access_token });
  const prices = await call({ resource: 'ops', op: 'prices', method: 'GET', query: { organization_id: nova }, token: tok.access_token });
  if (!(prices.body || []).some((p) => p.service_key === 'audit_consultation' && p.status === 'approved')) {
    const pr = await ops('prices', { action: 'create', service_key: 'audit_consultation', name: 'Nova Audit scoping call (complimentary)', description: 'A 30-minute call to scope your Nova Audit.', duration_minutes: 30, price_cents: 0, deposit_cents: 0 });
    if (pr.body?.row?.id) await ops('prices', { action: 'approve', id: pr.body.row.id });
  }
  const tpls = await call({ resource: 'ops', op: 'templates', method: 'GET', query: { organization_id: nova }, token: tok.access_token });
  if (!(tpls.body || []).some((t) => t.template_key === 'service_agreement' && t.status === 'approved')) {
    const tp = await ops('templates', { action: 'create', template_key: 'service_agreement', title: 'Nova Audit scoping call — booking confirmation', body: 'Booking between {{business_name}} and {{customer_name}}.\n\nService: {{service_name}}. Price: {{price}}.\n\nAppointment: {{appointment}}.\n\nThe call scopes your Nova Audit. Nothing is purchased by booking it.' });
    if (tp.body?.row?.id) await ops('templates', { action: 'approve', id: tp.body.row.id, acknowledge_not_legal_advice: true });
  }
  console.log(st.status === 200 && w.status === 200 ? '✓ Nova configured as its own first installation (form, hours, consultation service, booking agreement)' : `✗ Nova installation: settings ${st.status} ${JSON.stringify(st.body).slice(0, 120)} / wave1 ${w.status} ${JSON.stringify(w.body).slice(0, 120)}`);
  console.log(`✓ test owner and representative ready; credentials in ${path.basename(ACCOUNTS_FILE)} (not printed)`);
}

async function serve() {
  const env = readEnv(); Object.assign(process.env, env);
  const modules = new Map();
  const load = async (name) => { if (!modules.has(name)) modules.set(name, await import(`../../api/${name}.js`)); return modules.get(name); };
  const api = http.createServer(async (req, res) => {
    try {
      const url = new URL(req.url, `http://localhost:${API_PORT}`); const name = url.pathname.replace(/^\/api\//, '').replace(/\/$/, '');
      if (!/^[a-z-]+$/.test(name)) { res.statusCode = 404; return res.end('{}'); }
      const mod = await load(name); req.query = Object.fromEntries(url.searchParams);
      if (mod.config?.api?.bodyParser !== false) { const ch = []; for await (const x of req) ch.push(x); const t = Buffer.concat(ch).toString('utf8'); try { req.body = t ? JSON.parse(t) : {}; } catch { req.body = Object.fromEntries(new URLSearchParams(t)); } }
      const out = { setHeader: (k, v) => res.setHeader(k, v), status(code) { res.statusCode = code; return out; }, json(b) { res.setHeader('Content-Type', 'application/json'); res.end(JSON.stringify(b)); return out; }, send(b) { res.end(typeof b === 'string' || Buffer.isBuffer(b) ? b : JSON.stringify(b)); return out; }, end(b) { res.end(b); return out; }, get headersSent() { return res.headersSent; } };
      await mod.default(req, out);
    } catch (e) { console.error('[local api]', e.message); if (!res.headersSent) { res.statusCode = 500; res.end('{"error":"local api error"}'); } }
  });
  await new Promise((r) => api.listen(API_PORT, '127.0.0.1', r)); // the API itself is never on the network
  const lan = process.argv.includes('--lan');
  const lanIps = Object.values(os.networkInterfaces()).flat().filter((i) => i && i.family === 'IPv4' && !i.internal && !/^(169\.254|172\.(1[6-9]|2\d|3[01]))\./.test(i.address)).map((i) => i.address);
  if (lan) {
    // iPad / phone testing over the local Wi-Fi: the browser talks only to this app; it never needs Supabase's own port.
    process.env.VITE_SUPABASE_URL = 'same-origin';
    if (lanIps[0]) process.env.APP_BASE_URL = `http://${lanIps[0]}:${APP_PORT}`; // links in (local inbox) emails open on the iPad
  }
  const { createServer } = await import('vite');
  const vite = await createServer({
    configFile: path.join(ROOT, 'vite.config.js'),
    plugins: lan ? [supabaseGuard(env)] : [],
    server: { host: lan ? '0.0.0.0' : 'localhost', port: APP_PORT, strictPort: true, proxy: { '/api': `http://127.0.0.1:${API_PORT}` } },
  });
  await vite.listen();
  console.log(`✓ Nova local staging: http://localhost:${APP_PORT}  (API on ${API_PORT}, this computer only; Supabase Studio: http://127.0.0.1:54323)`);
  if (lan) console.log(`✓ On the same Wi-Fi (iPad): ${lanIps.map((ip) => `http://${ip}:${APP_PORT}`).join('  ') || 'no Wi-Fi address found'} — sign-in required; Supabase, Studio, the database and the mail inbox are NOT served here`);
}

// LAN mode only. Forwards exactly what the browser uses — sign-in (/auth/v1) and row-level-security reads (/rest/v1) —
// to local Supabase, and refuses everything else: admin endpoints, and any request carrying a key other than the
// public anon key or a signed-in user's token (so a leaked service-role key cannot be used through this port).
function supabaseGuard(env) {
  const target = new URL(env.SUPABASE_URL);
  return {
    name: 'nova-lan-supabase-guard',
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        const p = String(req.url || '').split('?')[0];
        if (!/^\/(auth|rest)\/v1\//.test(p)) return next();
        const deny = (why) => { res.statusCode = 403; res.setHeader('Content-Type', 'application/json'); res.end(JSON.stringify({ error: why })); };
        if (/^\/auth\/v1\/admin(\/|$)/.test(p)) return deny('Supabase administration is not available over the network');
        if (jwtRole(req.headers.apikey) !== 'anon') return deny('Only the public browser key is accepted here');
        const bearer = String(req.headers.authorization || '').replace(/^Bearer\s+/i, '');
        if (bearer && !['anon', 'authenticated'].includes(jwtRole(bearer))) return deny('Only a signed-in user token is accepted here');
        const fwd = http.request({ host: target.hostname, port: target.port, method: req.method, path: req.url, headers: { ...req.headers, host: target.host } }, (r) => { res.writeHead(r.statusCode || 502, r.headers); r.pipe(res); });
        fwd.on('error', () => { if (!res.headersSent) { res.statusCode = 502; res.end('{"error":"local Supabase is not reachable"}'); } });
        req.pipe(fwd);
      });
    },
  };
}

function worker() {
  const env = readEnv();
  const child = spawn(process.execPath, [path.join(ROOT, 'worker/index.mjs')], { env: { ...process.env, ...env, WORKER_ID: 'local-staging-worker' }, stdio: 'inherit' });
  child.on('exit', (code) => process.exit(code ?? 0));
}

// Rotate the LOCAL test-account passwords (e.g. after they were exposed in a photo). New random passwords are set through
// the local Auth admin API, every existing session of those accounts is ended, and the git-ignored accounts file is
// rewritten. Nothing is printed. Refuses anything that is not the local stack.
async function rotatePasswords() {
  const env = readEnv();
  if (!/^http:\/\/127\.0\.0\.1:/.test(env.SUPABASE_URL || '')) die('refusing: not the local stack');
  if (!fs.existsSync(ACCOUNTS_FILE)) die(`${path.basename(ACCOUNTS_FILE)} not found; run provision first`);
  const accounts = Object.fromEntries(fs.readFileSync(ACCOUNTS_FILE, 'utf8').split(/\r?\n/).filter((l) => /^[A-Z_]+=/.test(l)).map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)]));
  const c = await pgClient(env); let n = 0;
  for (const key of Object.keys(accounts).filter((k) => k.endsWith('_EMAIL'))) {
    const email = accounts[key]; if (!/@nova-local\.test$/.test(email)) continue; // local test accounts only
    const id = (await c.query('select id from auth.users where email=$1', [email])).rows[0]?.id; if (!id) continue;
    const password = `Nv-${crypto.randomBytes(15).toString('base64url')}`;
    const r = await fetch(`${env.SUPABASE_URL}/auth/v1/admin/users/${id}`, { method: 'PUT', headers: { apikey: env.SUPABASE_SERVICE_ROLE_KEY, Authorization: `Bearer ${env.SUPABASE_SERVICE_ROLE_KEY}`, 'Content-Type': 'application/json' }, body: JSON.stringify({ password }) });
    if (!r.ok) { await c.end(); die(`password change refused for ${key} (${r.status}); nothing else changed for it`); }
    await c.query('delete from auth.refresh_tokens where user_id::text=$1::text', [id]).catch(() => {});
    await c.query('delete from auth.sessions where user_id=$1', [id]).catch(() => {});
    accounts[key.replace(/_EMAIL$/, '_PASSWORD')] = password; n++;
  }
  await c.end();
  fs.writeFileSync(ACCOUNTS_FILE, `# LOCAL STAGING test accounts — git-ignored; local stack only. Rotated ${new Date().toISOString()}.\n${Object.entries(accounts).map(([k, v]) => `${k}=${v}`).join('\n')}\n`, { mode: 0o600 });
  console.log(`✓ rotated ${n} local test password(s); sessions ended; new values written to ${path.basename(ACCOUNTS_FILE)} (not printed)`);
}

const run = { check, up, env: writeEnv, migrate, provision, serve, worker, 'rotate-passwords': rotatePasswords, down: () => supabase(['stop']) }[cmd];
if (!run) die('usage: node scripts/local/staging.mjs check|up|env|migrate|provision|serve|worker|rotate-passwords|down');
await run();
